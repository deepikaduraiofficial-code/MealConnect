/**
 * Resolves the accurate food image matching a food item's name and category.
 * Priority: uploaded/custom image (always preserved) → exact name match → keyword match → category fallback.
 */
export function getMatchingFoodImage(foodName = '', category = '', currentImage = '') {
  // 1. If an image is provided on the item (e.g. uploaded base64 data URL, blob, or file path), ALWAYS preserve and use it!
  if (currentImage && typeof currentImage === 'string' && currentImage.trim().length > 0) {
    return currentImage;
  }

  const normalizedName = (foodName || '').toLowerCase().trim();

  // 2. Exact name match from catalog map (for initial mock items without custom upload)
  if (FOOD_IMAGE_MAP[normalizedName]) {
    return FOOD_IMAGE_MAP[normalizedName];
  }

  // 3. Keyword matching rule based on food name
  for (const rule of KEYWORD_IMAGE_RULES) {
    if (rule.keywords.some(kw => normalizedName.includes(kw))) {
      return rule.url;
    }
  }

  // 4. Category fallback image
  if (category && CATEGORY_DEFAULT_IMAGES[category]) {
    return CATEGORY_DEFAULT_IMAGES[category];
  }

  // 5. Ultimate fallback
  return "/food-images/vegetable_biryani_salan.jpg";
}
